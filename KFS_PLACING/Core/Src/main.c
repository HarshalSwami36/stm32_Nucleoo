void PCA9685_Init(void) {
    uint8_t data[2];

    // 1. Put PCA to Sleep to set Frequency
    data[0] = MODE1_REG;
    data[1] = 0x10;
    HAL_I2C_Mem_Write(&hi2c1, PCA9685_ADDR, data[0], 1, &data[1], 1, 100);

    // 2. Set to 50Hz (Prescale = 121)
    data[0] = PRESCALE_REG;
    data[1] = 121;
    HAL_I2C_Mem_Write(&hi2c1, PCA9685_ADDR, data[0], 1, &data[1], 1, 100);

    // 3. Wake up PCA
    data[0] = MODE1_REG;
    data[1] = 0xA1; // Restart + Auto-Increment
    HAL_I2C_Mem_Write(&hi2c1, PCA9685_ADDR, data[0], 1, &data[1], 1, 100);
    HAL_Delay(5);
}

void Set_Servo_Angle(uint8_t channel, uint16_t angle) {
    // Map 0-180 angle to pulse width (approx 150-600)
    uint16_t pulse = 150 + (angle * 450 / 180);
    uint8_t buffer[4];

    buffer[0] = 0x00; // ON_L
    buffer[1] = 0x00; // ON_H
    buffer[2] = pulse & 0xFF; // OFF_L
    buffer[3] = pulse >> 8;   // OFF_H

    HAL_I2C_Mem_Write(&hi2c1, PCA9685_ADDR, LED0_ON_L + (4 * channel), 1, buffer, 4, 100);
}

void Set_Motor_Speed(int16_t speed) {
    if (speed > 0) {
        __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_1, speed);
        __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_2, 0);
    } else if (speed < 0) {
        __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_1, 0);
        __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_2, -speed);
    } else {
        __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_1, 0);
        __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_2, 0);
    }
}

void UART_Send(char* message) {
    HAL_UART_Transmit(&huart3, (uint8_t*)message, strlen(message), 100);
}

