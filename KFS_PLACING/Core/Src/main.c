/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{
  /* USER CODE BEGIN 1 */
  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/
  HAL_Init();

  /* USER CODE BEGIN Init */
  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */
  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_USART3_UART_Init();
  MX_I2C1_Init();
  MX_TIM2_Init();

  /* USER CODE BEGIN 2 */
  // 1. Initialize PCA9685 (Wake up and set to 50Hz)
  PCA9685_Init();

  // 2. Start PWM for Motor (TIM2 Channels 1 & 2)
  HAL_TIM_PWM_Start(&htim2, TIM_CHANNEL_1);
  HAL_TIM_PWM_Start(&htim2, TIM_CHANNEL_2);

  UART_Send("STM32 Control Ready. Use 1, 2, 3, 4, or 0.\r\n");
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    // Check for UART command (Timeout 10ms for non-blocking feel)
    if (HAL_UART_Receive(&huart3, &rx_byte, 1, 10) == HAL_OK)
    {
        switch(rx_byte)
        {
            case '1': // Open Flap
                Set_Servo_Angle(12, 90);
                UART_Send("Flap Opened\r\n");
                break;

            case '2': // Close Flap
                Set_Servo_Angle(12, 0);
                UART_Send("Flap Closed\r\n");
                break;

            case '3': // Forward
                Set_Motor_Speed(200);
                UART_Send("Forward\r\n");
                break;

            case '4': // Backward
                Set_Motor_Speed(-200);
                UART_Send("Backward\r\n");
                break;

            case '0': // Stop
                Set_Motor_Speed(0);
                UART_Send("Stopped\r\n");
                break;
        }
    }
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

